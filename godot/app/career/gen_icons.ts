// Writes career_icons.gd: the web's line icons (src/ui/icons.ts) as whole SVG documents, for the
// career screens to rasterize. Re-run after icons.ts changes:
//   node --experimental-transform-types --no-warnings --import <tsrun register.mjs> godot/app/career/gen_icons.ts
import fs from 'node:fs';
import { ABILITY_ICON, COMPANY_ICON, ICON, PASSIVE_ICON, SLOT_ICON } from '../../../src/ui/icons.ts';

const dict = (name: string, doc: string, d: Record<string, string | undefined>) =>
  `## ${doc}\nconst ${name} := {\n${Object.entries(d)
    .filter(([, v]) => v)
    .map(([k, v]) => `\t${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join('\n')}\n}\n`;
const out = `## GENERATED by gen_icons.ts from src/ui/icons.ts: don't edit, re-run it.
## Every icon is a whole 24-unit SVG drawn in currentColor (CareerKit.icon rasterizes it in white
## and tints it).
class_name CareerIcons
extends RefCounted

${dict('ICON', 'icons.ts ICON', ICON)}
${dict('SLOT', 'icons.ts SLOT_ICON: a part slot', SLOT_ICON)}
${dict('COMPANY', 'icons.ts COMPANY_ICON: the makers\' logos', COMPANY_ICON)}
${dict('ABILITY', 'icons.ts ABILITY_ICON: special moves', ABILITY_ICON)}
${dict('PASSIVE', 'icons.ts PASSIVE_ICON: passives', PASSIVE_ICON)}`;
fs.writeFileSync(new URL('./career_icons.gd', import.meta.url), out);
console.log('career_icons.gd written');
