// Writes godot/app/ui/icons.gd from src/ui/icons.ts (every icon set, as [body, extra svg attributes]).
//   node --experimental-transform-types --no-warnings --import <tsrun register.mjs> godot/app/ui/gen_icons.ts
import { writeFileSync } from 'node:fs';
import { ABILITY_ICON, COMPANY_ICON, ICON, PASSIVE_ICON, SLOT_ICON } from '../../../src/ui/icons.ts';

const HEAD = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" ';
const split = (s: string): [string, string] => {
  if (!s.startsWith(HEAD) || !s.endsWith('</svg>')) throw new Error('unexpected svg: ' + s.slice(0, 80));
  const rest = s.slice(HEAD.length, -'</svg>'.length);
  const gt = rest.indexOf('>');
  return [rest.slice(gt + 1), rest.slice(0, gt).trim()];
};
const q = (s: string) => JSON.stringify(s);
const dict = (name: string, doc: string, set: Record<string, string | undefined>) => {
  const rows = Object.entries(set)
    .filter(([, v]) => !!v)
    .map(([k, v]) => {
      const [body, extra] = split(v!);
      return `\t${q(k)}: [${q(body)}, ${q(extra)}],`;
    });
  return `## ${doc}\nconst ${name} := {\n${rows.join('\n')}\n}\n`;
};
const out = `## The web game's line icons (src/ui/icons.ts), every set, generated by gen_icons.ts: don't edit,
## re-run it. Each is [svg body, extra svg attributes] on a 24-unit grid, drawn in currentColor
## (rasterized white and tinted). UiTheme.icon(name) finds them by name: "wrench", "slot:head",
## "co:lumen", "ab:haymaker", "pa:composure".
class_name Icons
extends RefCounted

${dict('ICON', 'icons.ts ICON', ICON as Record<string, string>)}
${dict('SLOT', 'icons.ts SLOT_ICON: a part slot', SLOT_ICON)}
${dict('COMPANY', 'icons.ts COMPANY_ICON: the maker logos', COMPANY_ICON)}
${dict('ABILITY', 'icons.ts ABILITY_ICON: the special moves', ABILITY_ICON)}
${dict('PASSIVE', 'icons.ts PASSIVE_ICON: the passives', PASSIVE_ICON)}

## [body, extra] for an icon name ("slot:", "co:", "ab:" or "pa:" picks a set), or null.
static func find(name: String):
	var at := name.find(":")
	if at < 0:
		return ICON.get(name)
	var key := name.substr(at + 1)
	match name.substr(0, at):
		"slot":
			return SLOT.get(key)
		"co":
			return COMPANY.get(key)
		"ab":
			return ABILITY.get(key)
		"pa":
			return PASSIVE.get(key)
	return null
`;
writeFileSync(new URL('./icons.gd', import.meta.url), out);
console.log('wrote icons.gd');
