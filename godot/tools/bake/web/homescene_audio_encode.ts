// Second half of the home screens' sound bake (see homescene_audio.ts): encodes the raw renders in
// godot/assets/home/audio/_raw/ to Ogg Vorbis next to it, writes the manifest as
// godot/render/home/home_sound_bank.gd (a script, so it ships without an export filter) and drops _raw.
//   node --experimental-strip-types godot/tools/bake/web/homescene_audio_encode.ts
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../../..');
const DIR = path.join(ROOT, 'godot/assets/home/audio');
const RAW = path.join(DIR, '_raw');
const m = JSON.parse(fs.readFileSync(path.join(RAW, 'manifest.json'), 'utf8'));

/** Vorbis quality per clip: the tunes and the ringtone want more than noise beds do. */
function quality(name: string) {
  if (name.endsWith('_music') || name === 'ring') return 5;
  if (name.endsWith('_bed')) return 3;
  return 4;
}

for (const f of fs.readdirSync(DIR)) if (f.endsWith('.ogg')) fs.rmSync(path.join(DIR, f));
let bytes = 0;
for (const c of m.clips) {
  const out = path.join(DIR, `${c.name}.ogg`);
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-f', 'f32le', '-ar', String(m.rate), '-ac', String(c.channels), '-i', path.join(RAW, `${c.name}.f32`), '-c:a', 'libvorbis', '-q:a', String(quality(c.name)), out]);
  bytes += fs.statSync(out).size;
}

const num = (x: number) => (Number.isInteger(x) ? `${x}.0` : String(+x.toPrecision(7)));
const lines = [
  "## The home screens' sound manifest, generated by tools/bake/web/homescene_audio_encode.ts from the",
  "## web game's own audio code (src/audio/homeSound.ts, sfx.ts): do not edit, re-bake.",
  'class_name HomeSoundBank',
  '',
  '## Sample rate of every clip (Hz).',
  `const RATE := ${m.rate}`,
  '## The bag hit is baked at these strengths (bag_hit_<i>_<v>.ogg).',
  `const BAG_KS := [${m.bagKs.map(num).join(', ')}]`,
  '## Every clip: name -> [channels, gain its samples were normalised by, seconds, loop length (0: one-shot)].',
  'const CLIPS := {',
  ...m.clips.map((c: { name: string; channels: number; gain: number; dur: number; loop: number }) => `\t"${c.name}": [${c.channels}, ${num(c.gain)}, ${num(c.dur)}, ${num(c.loop)}],`),
  '}',
  '',
];
fs.writeFileSync(path.join(ROOT, 'godot/render/home/home_sound_bank.gd'), lines.join('\n'));
fs.rmSync(RAW, { recursive: true });
console.log(`${m.clips.length} clips, ${(bytes / 1e6).toFixed(2)} MB of ogg`);
