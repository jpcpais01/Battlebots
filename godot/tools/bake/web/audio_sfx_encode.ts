// Second half of the sound kit's bake (see audio_sfx.ts): encodes the raw renders in
// godot/assets/audio/sfx/_raw/ to Ogg Vorbis next to it, writes the manifest as
// godot/audio/sfx_bank.gd (a script, so it ships without an export filter) and drops _raw.
//   node --experimental-strip-types godot/tools/bake/web/audio_sfx_encode.ts
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../../..');
const DIR = path.join(ROOT, 'godot/assets/audio/sfx');
const RAW = path.join(DIR, '_raw');
const m = JSON.parse(fs.readFileSync(path.join(RAW, 'manifest.json'), 'utf8'));

/** Vorbis quality per clip: noise and drums hide coding noise well, the music and the bell less so. */
function quality(name: string) {
  if (name.startsWith('walkon_') || name.startsWith('chant_') || name === 'bell' || name === 'fist_bump') return 5;
  if (name.startsWith('impw_')) return 2;
  return 4;
}

for (const f of fs.readdirSync(DIR)) if (f.endsWith('.ogg')) fs.rmSync(path.join(DIR, f));
let bytes = 0;
for (const c of m.clips) {
  const out = path.join(DIR, `${c.name}.ogg`);
  // (an impact's slap send is low-passed at 2.4 kHz: 16 kHz holds all of it)
  const rate = c.name.startsWith('impw_') ? ['-ar', '16000'] : [];
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-f', 'f32le', '-ar', String(m.rate), '-ac', String(c.channels), '-i', path.join(RAW, `${c.name}.f32`), ...rate, '-c:a', 'libvorbis', '-q:a', String(quality(c.name)), out]);
  bytes += fs.statSync(out).size;
}

const num = (x: number) => (Number.isInteger(x) ? `${x}.0` : String(+x.toPrecision(7)));
const arr = (a: number[]) => `[${a.map(num).join(', ')}]`;
const lines = [
  '## The fight sound kit\'s manifest, generated by tools/bake/web/audio_sfx_encode.ts from the',
  '## web game\'s own audio code (src/audio/sfx.ts, impacts.ts, walkOn.ts): do not edit, re-bake.',
  'class_name SfxBank',
  '',
  `## Sample rate of every clip (Hz).`,
  `const RATE := ${m.rate}`,
  `## Silence in front of every impact clip (s), for its flam.`,
  `const LEAD := ${num(m.lead)}`,
  `## Variations of each impacts.ts kind (imp_<kind>_<n>.ogg).`,
  `const BANK := {${Object.entries(m.bank).map(([k, n]) => `"${k}": ${n}`).join(', ')}}`,
  `## Burst lengths the steam hiss is baked at (hiss_<i>_<v>.ogg), and the level k it was baked at.`,
  `const HISS_DURS := ${arr(m.hissDurs)}`,
  `const HISS_K := ${num(m.hissK)}`,
  `## The k the thud's and the big hit's sub drops are baked at (thud_tone_<i>, hit_tone_<i>).`,
  `const THUD_KS := ${arr(m.thudKs)}`,
  `const HIT_KS := ${arr(m.hitKs)}`,
  `## Seconds into a walk-on theme where its drop lands (walkOn.ts BUILD: the lift locking at the top).`,
  `const BUILD := ${num(m.build)}`,
  `const WALK_ONS := [${m.walkOns.map((w: string) => `"${w}"`).join(', ')}]`,
  `## Every clip: name -> [channels, gain its samples were normalised by, seconds].`,
  'const CLIPS := {',
  ...m.clips.map((c: { name: string; channels: number; gain: number; dur: number }) => `\t"${c.name}": [${c.channels}, ${num(c.gain)}, ${num(c.dur)}],`),
  '}',
  '',
];
fs.writeFileSync(path.join(ROOT, 'godot/audio/sfx_bank.gd'), lines.join('\n'));
fs.rmSync(RAW, { recursive: true });
console.log(`${m.clips.length} clips, ${(bytes / 1e6).toFixed(2)} MB of ogg`);
